// swift-tools-version: 6.0

import PackageDescription

// Prebuilt livesplit-core static libraries live in Vendor/livesplit-core/<platform>.
// Rebuild them with scripts/build-livesplit-core.sh.
let vendor = Context.packageDirectory + "/Vendor/livesplit-core"

let package = Package(
    name: "Splitter",
    platforms: [
        .iOS(.v17),
        .macOS(.v14),
    ],
    products: [
        // xtool: exactly one library product, representing the main app.
        .library(name: "Splitter", targets: ["SplitterApp"]),
    ],
    targets: [
        // C API of livesplit-core (header generated by livesplit-core's bind_gen).
        .target(
            name: "CLiveSplitCore",
            linkerSettings: [
                .linkedLibrary("livesplit_core"),
                .unsafeFlags(["-L", vendor + "/ios-arm64"], .when(platforms: [.iOS])),
                .unsafeFlags(["-L", vendor + "/linux-x86_64"], .when(platforms: [.linux])),
                .linkedLibrary("m", .when(platforms: [.linux])),
                .linkedLibrary("dl", .when(platforms: [.linux])),
            ]
        ),
        // Swift bindings generated by livesplit-core's bind_gen (unmodified).
        .target(
            name: "LiveSplitCore",
            dependencies: ["CLiveSplitCore"],
            swiftSettings: [.swiftLanguageMode(.v5)]
        ),
        // UI-independent timer logic. Builds on Linux too, so it can be tested here.
        .target(
            name: "SplitterCore",
            dependencies: ["LiveSplitCore"]
        ),
        // SwiftUI app.
        .target(
            name: "SplitterApp",
            dependencies: ["SplitterCore"]
        ),
        .testTarget(
            name: "SplitterCoreTests",
            dependencies: ["SplitterCore"],
            resources: [.copy("Fixtures")]
        ),
    ]
)
